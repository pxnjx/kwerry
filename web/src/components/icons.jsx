// Phosphor "regular" glyphs are single FILLED paths — not stroked outlines.
// Painting them with fill="none" stroke=... was what made every icon look
// like a doubled, hairy outline.
//
// Usage: <DownloadIcon /> — the class does the work. Size tracks 1em so an
// icon stays aligned with the label next to it; pass a className (e.g. "spin")
// for extra styling. Decorative by default; pass title when the icon alone
// carries meaning.

